def fix_experiment(body: str) -> str:
    body = _clean_attrs(body)
    body = re.sub(
        r'<p>\s*Видеозапись:\s*<a href="([^"]+)">[^<]*</a>\s*</p>',
        r'<ul><li>Видеозапись — <a href="\1">смотреть</a></li></ul>',
        body,
        count=1,
    )
    marker = "<h2>6. Быстрый чек-лист ошибок</h2>"
    if marker in body:
        head, tail = body.split(marker, 1)
        items = re.findall(r"<p>(.*?)</p>", tail, flags=re.S)
        lis = "".join(f"<li>{item.strip()}</li>" for item in items if item.strip())
        body = head + marker + f"<ul>{lis}</ul>"
    return body


def fix_articles_safe(body: str) -> str:
    body = _clean_attrs(body)
    # Remove first document-only paragraphs and lecturer mashup
    body = re.sub(
        r'^(?:\s*<p>\s*<a linktype="document" id="\d+">[^<]*</a>\s*</p>\s*)+',
        "",
        body,
    )
    body = re.sub(
        r'<p>\s*<a linktype="document" id="4">Образец</a><b><br/>Лектор:</b>.*?</p>\s*',
        "",
        body,
        count=1,
        flags=re.S,
    )
    body = re.sub(
        r"<p>\s*Примеры строились на лазерном дифракционном анализаторе размеров частиц\..*?</p>\s*",
        "",
        body,
        count=1,
        flags=re.S,
    )
    body = body.replace(
        '<a href="https://scholar.google.com/">https://scholar.google.com/</a>',
        '<a href="https://scholar.google.com/">Google Scholar</a>',
    )
    marker = '<h3>9. Краткий итог (слайд «Заключение»)</h3>'
    if marker in body:
        head, tail = body.split(marker, 1)
        items = re.findall(r"<p>(.*?)</p>", tail, flags=re.S)
        lis = "".join(f"<li>{item.strip()}</li>" for item in items if item.strip())
        body = head + "<h2>Краткий итог</h2>" + f"<ul>{lis}</ul>"
    # Turn top-level numbered h3 into h2
    body = re.sub(
        r"<h3>(\d+\.\s[^<]+)</h3>",
        r"<h2>\1</h2>",
        body,
    )
    return ARTICLES_HEAD + "\n" + body


def fix_theory(body: str) -> str:
    body = _clean_attrs(body)
    body = re.sub(
        r'^<h3>\s*<a linktype="document" id="5">Презентация Вебинара</a>\s*</h3>\s*',
        "",
        body,
    )
    body = re.sub(
        r'<h3>\s*Видеозапись:\s*<a href="([^"]+)">[^<]*</a>\s*<br\s*/?>\s*<br\s*/?>\s*Главные тезисы вебинара\s*</h3>',
        r"<h2>Главные тезисы</h2>",
        body,
        count=1,
    )
    body = re.sub(
        r"<h3>(\d+\.\s[^<]+)</h3>",
        r"<h2>\1</h2>",
        body,
    )
    body = re.sub(
        r"<h3>(Краткий чек-лист для команды)</h3>",
        r"<h2>\1</h2>",
        body,
    )
    return (
        '<ul>'
        '<li>Презентация — <a linktype="document" id="5">скачать</a></li>'
        '<li>Видеозапись — <a href="https://vkvideo.ru/video-222342853_456239072">смотреть</a></li>'
        "</ul>\n"
        + body
    )


class Command(BaseCommand):
    help = "Оформить все страницы материалов единообразно"

    def handle(self, *args, **options):
        mapping = {
            "сборник-видео": None,  # already good
            "вводный-вебинар": lambda _b: INTRO_WEBINAR,
            "о-физическом-эксперименте": fix_experiment,
            "читаем-научные-статьи": fix_articles_safe,
            "построение-теоретической-модели": fix_theory,
            "reference-kit-2026-2027": lambda _b: REFERENCE,
        }
        for slug, fixer in mapping.items():
            page = MaterialPage.objects.filter(slug=slug).first()
            if not page:
                self.stderr.write(f"нет: {slug}")
                continue
            if fixer is None:
                self.stdout.write(f"пропуск (уже ок): {slug}")
                continue
            page.body = fixer(page.body or "")
            page.save_revision().publish()
            self.stdout.write(self.style.SUCCESS(f"ок: {slug}"))

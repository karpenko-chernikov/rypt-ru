class Command(BaseCommand):
    help = "Заменить демо-регионы на реальные данные карты России"

    def handle(self, *args, **options):
        home = HomePage.objects.first()
        if not home:
            self.stderr.write("Нет главной страницы.")
            return
        page = RussiaTournamentsPage.objects.child_of(home).first()
        if not page:
            page = RussiaTournamentsPage(
                title="Турниры в России",
                slug="russia",
                intro=(
                    "<p>Региональные турниры по субъектам РФ. "
                    "Наведите на область — справа откроется карточка турнира.</p>"
                ),
            )
            home.add_child(instance=page)
        page.regions.all().delete()
        for i, demo in enumerate(REAL_REGIONS):
            problems = demo["problems"]
            fields = {k: v for k, v in demo.items() if k != "problems"}
            reg = RegionalTournament(page=page, sort_order=i, **fields)
            page.regions.add(reg)
            reg.save()
            for j, (num, title, statement) in enumerate(problems):
                RegionalProblem.objects.create(
                    tournament=reg,
                    sort_order=j,
                    number=num,
                    title=title,
                    statement=statement,
                )
        page.save_revision().publish()
        self.stdout.write(
            self.style.SUCCESS(
                f"Готово: {page.regions.count()} регион(ов), демо удалены."
            )
        )
